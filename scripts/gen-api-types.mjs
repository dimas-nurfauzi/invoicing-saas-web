// Generates src/api/schema.d.ts from the committed openapi.json snapshot.
//
// springdoc documents BigDecimal as `type: number`, but the backend sends and accepts money,
// quantities and percentages as decimal strings ("1500000.00", @JsonFormat(shape = STRING)).
// In this API every `number` without a `format` is a BigDecimal (integers are `type: integer`),
// so they become `string` here: the frontend never does float math on money.
import { writeFileSync } from 'node:fs'
import openapiTS, { astToString } from 'openapi-typescript'
import ts from 'typescript'

const DECIMAL_STRING = ts.factory.createKeywordTypeNode(ts.SyntaxKind.StringKeyword)

const ast = await openapiTS(new URL('../openapi.json', import.meta.url), {
  transform(schemaObject) {
    if (schemaObject.type === 'number' && !schemaObject.format) return DECIMAL_STRING
    return undefined
  },
})

const banner =
  '// Generated by scripts/gen-api-types.mjs from openapi.json. Do not edit; run `npm run gen:api`.\n\n'
writeFileSync(new URL('../src/api/schema.d.ts', import.meta.url), banner + astToString(ast))
console.log('src/api/schema.d.ts written')
